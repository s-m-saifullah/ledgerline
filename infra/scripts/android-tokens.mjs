/**
 * Writes the Android app's colour palettes from the web design tokens (packages/ui/src/tokens.css), so both
 * apps use the same colours and the accent shades come from the same OKLCH seed (ADR 0043).
 *
 *   node infra/scripts/android-tokens.mjs          write the Kotlin file
 *   node infra/scripts/android-tokens.mjs --check  fail if the file is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const tokensPath = join(root, "packages/ui/src/tokens.css");
export const outputPath = join(
  root,
  "apps/android/app/src/main/kotlin/app/ledgerline/android/ui/theme/LedgerlinePalette.kt",
);

const clamp01 = (value) => Math.min(1, Math.max(0, value));

/** OKLCH (lightness 0..1, chroma, hue in degrees) to an sRGB hex colour; out-of-gamut channels are clamped. */
export function oklchToHex(lightness, chroma, hue) {
  const radians = (hue * Math.PI) / 180;
  const a = chroma * Math.cos(radians);
  const b = chroma * Math.sin(radians);
  const l = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (lightness - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const linear = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  const encode = (value) => {
    const v = clamp01(value);
    return v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
  };
  const channel = (value) =>
    Math.round(encode(value) * 255)
      .toString(16)
      .padStart(2, "0");
  return `#${linear.map(channel).join("")}`;
}

function blocks(css) {
  const light = /:root\s*\{([^}]*)\}/.exec(css)?.[1];
  const dark = /:root\[data-theme="dark"\]\s*\{([^}]*)\}/.exec(css)?.[1];
  if (!light || !dark)
    throw new Error("tokens.css: light or dark block not found");
  return { light, dark };
}

function declarations(block) {
  const result = {};
  for (const match of block.matchAll(/--([a-z-]+):\s*([^;]+);/g))
    result[match[1]] = match[2].trim();
  return result;
}

/** The colours a palette needs, read from the token blocks. */
export function palettes(css) {
  const { light, dark } = blocks(css);
  const lightTokens = declarations(light);
  const darkTokens = declarations(dark);
  const seed = /oklch\(([\d.]+) ([\d.]+) ([\d.]+)\)/.exec(
    lightTokens["accent-seed"] ?? "",
  );
  if (!seed)
    throw new Error("tokens.css: --accent-seed is not an oklch() colour");
  const seedChroma = Number(seed[2]);
  const seedHue = Number(seed[3]);

  const resolve = (value, name) => {
    if (value === "white") return "#ffffff";
    if (/^#[0-9a-f]{6}$/i.test(value)) return value.toLowerCase();
    const derived =
      /^oklch\(from var\(--accent-seed\) ([\d.]+) (c|[\d.]+) h\)$/.exec(value);
    if (derived)
      return oklchToHex(
        Number(derived[1]),
        derived[2] === "c" ? seedChroma : Number(derived[2]),
        seedHue,
      );
    throw new Error(`tokens.css: cannot read --${name}: ${value}`);
  };

  const names = [
    "accent",
    "accent-soft",
    "accent-foreground",
    "background",
    "surface",
    "border",
    "field-border",
    "text",
    "muted",
    "danger",
    "danger-foreground",
    "positive",
    "warning",
  ];
  const build = (tokens, fallback) =>
    Object.fromEntries(
      names.map((name) => {
        const value = tokens[name] ?? fallback[name];
        if (value === undefined)
          throw new Error(`tokens.css: --${name} is missing`);
        return [name, resolve(value, name)];
      }),
    );
  return {
    light: build(lightTokens, {}),
    dark: build(darkTokens, lightTokens),
  };
}

const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

/** The Kotlin source for the palettes in the given tokens.css text. */
export function generate(css) {
  const { light, dark } = palettes(css);
  const fields = Object.keys(light).map(camel);
  const color = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
  const palette = (name, values) =>
    `val ${name} = LedgerlinePalette(\n${Object.entries(values)
      .map(([key, hex]) => `    ${camel(key)} = ${color(hex)},`)
      .join("\n")}\n)`;
  return `// Generated by infra/scripts/android-tokens.mjs from packages/ui/src/tokens.css. Do not edit.
package app.ledgerline.android.ui.theme

import androidx.compose.ui.graphics.Color

data class LedgerlinePalette(
${fields.map((field) => `    val ${field}: Color,`).join("\n")}
)

${palette("LightPalette", light)}

${palette("DarkPalette", dark)}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = generate(readFileSync(tokensPath, "utf8"));
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(outputPath, "utf8");
    } catch {}
    if (current !== source) {
      console.error(
        "LedgerlinePalette.kt is out of date: run node infra/scripts/android-tokens.mjs",
      );
      process.exit(1);
    }
  } else {
    writeFileSync(outputPath, source);
  }
}
